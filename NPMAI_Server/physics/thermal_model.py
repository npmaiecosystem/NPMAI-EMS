"""
Layer 3 core physics: back-calculate a joint's effective contact
resistance from a temperature reading, and forward-calculate the
temperature rise a HEALTHY joint would produce at the same current -
the residual between "expected" and "actual" T_hotspot is the real
fault signal (raw temperature confounds with load level: a lightly
loaded loose joint and a heavily loaded healthy joint can show the same
absolute T_hotspot).

---- The lumped thermal-resistance model ----

Steady-state energy balance at a joint: all the I^2*R heat generated by
contact resistance must leave via convection + radiation to the
surrounding air, or the joint keeps heating indefinitely. At steady
state:

    P_dissipated = I_rms^2 * R_effective                      (Joule heating)
    P_dissipated = (T_hotspot - T_ambient) / theta_thermal     (Newton's law of
                                                                 cooling, lumped form)

Setting these equal and solving for R_effective:

    R_effective = (T_hotspot - T_ambient) / (I_rms^2 * theta_thermal)

This is the same lumped-thermal-resistance approach already validated
manually against a known load (per the pilot's own "ratio ~1.01 vs
manual calc" check). CoolProp's role here is specifically to compute
theta_thermal (the joint-to-ambient thermal resistance, K/W) from real
air properties at the reading's actual film temperature, instead of a
single fixed/guessed calibration constant - so theta_thermal adapts
correctly as ambient conditions (e.g. seasonal HVAC setpoint changes)
shift, rather than baking in one value that's only valid at whatever
temperature it was calibrated at.

---- Where theta_thermal comes from ----

theta_thermal = 1 / (h_total * A), where:
  - A is the joint's exposed surface area (m^2) - per-breaker config,
    see app/breaker_thermal_config.py.
  - h_total = h_convective + h_radiative (W/m^2/K):
      - h_convective: Churchill-Chu natural-convection correlation
        (Churchill & Chu, 1975 - a standard textbook correlation, valid
        across the full laminar-to-turbulent Rayleigh range, which is
        why it's used here instead of a regime-specific correlation
        that would need its own Ra threshold check). Air viscosity,
        conductivity, density and specific heat come from CoolProp's
        PropsSI at the film temperature.
      - h_radiative: linearized radiative coefficient, valid for the
        modest temperature differences (a few tens of C) this system is
        built to detect - see the module-level note in
        app/physics/tespy_model.py about the Delta-T severity scale.

This is a simplification relative to a full CFD/radiation treatment of
the joint's real (irregular) geometry - a vertical-flat-plate
correlation is a reasonable engineering approximation for a compact
terminal/lug, not an exact solution. If manual calibration data
diverges meaningfully from this model's theta_thermal for a specific
joint, use BreakerThermalConfig.theta_thermal_override_k_per_w
(app/breaker_thermal_config.py) to substitute a directly-measured value
for that joint instead of the correlation.
"""
from CoolProp.CoolProp import PropsSI

_STEFAN_BOLTZMANN = 5.670374419e-8  # W/m^2/K^4
_GRAVITY = 9.81                     # m/s^2
_ATMOSPHERIC_PRESSURE_PA = 101325.0
_MIN_DELTA_T_FOR_CORRELATION = 0.1  # K floor - avoids Ra=0 / divide-by-zero at delta_t=0


def compute_theta_thermal(
    t_ambient_c: float,
    t_hotspot_c: float,
    area_m2: float,
    char_length_m: float,
    emissivity: float = 0.9,
) -> float:
    """
    Returns theta_thermal in K/W. See module docstring for derivation.
    Raises whatever CoolProp/math raises on nonsensical inputs (e.g. a
    film temperature outside air's valid property range) - callers
    (app/physics_processor.py) catch this and mark the reading
    'physics_failed' rather than crashing the service.
    """
    delta_t = max(t_hotspot_c - t_ambient_c, _MIN_DELTA_T_FOR_CORRELATION)
    t_film_k = (t_ambient_c + t_hotspot_c) / 2.0 + 273.15

    k = PropsSI("L", "T", t_film_k, "P", _ATMOSPHERIC_PRESSURE_PA, "Air")    # thermal conductivity, W/m/K
    mu = PropsSI("V", "T", t_film_k, "P", _ATMOSPHERIC_PRESSURE_PA, "Air")   # dynamic viscosity, Pa*s
    rho = PropsSI("D", "T", t_film_k, "P", _ATMOSPHERIC_PRESSURE_PA, "Air")  # density, kg/m^3
    cp = PropsSI("C", "T", t_film_k, "P", _ATMOSPHERIC_PRESSURE_PA, "Air")   # specific heat, J/kg/K

    nu = mu / rho             # kinematic viscosity, m^2/s
    alpha = k / (rho * cp)    # thermal diffusivity, m^2/s
    pr = nu / alpha           # Prandtl number
    beta = 1.0 / t_film_k     # ideal-gas volumetric thermal expansion coefficient, 1/K

    rayleigh = _GRAVITY * beta * delta_t * char_length_m ** 3 / (nu * alpha)

    # Churchill-Chu correlation (vertical plate, valid across all Ra):
    nusselt = (
        0.825
        + (0.387 * rayleigh ** (1.0 / 6.0))
        / (1.0 + (0.492 / pr) ** (9.0 / 16.0)) ** (8.0 / 27.0)
    ) ** 2

    h_convective = nusselt * k / char_length_m
    h_radiative = 4.0 * emissivity * _STEFAN_BOLTZMANN * t_film_k ** 3
    h_total = h_convective + h_radiative

    return 1.0 / (h_total * area_m2)


def compute_r_effective(i_rms: float, t_hotspot: float, t_ambient: float, theta_thermal: float) -> float:
    """
    R_effective = (T_hotspot - T_ambient) / (I_rms^2 * theta_thermal).
    Clamped to 0.0 when T_hotspot <= T_ambient: a negative resistance
    isn't physically meaningful - that's sensor noise around a healthy,
    lightly-loaded joint, not a signal.
    """
    delta_t = t_hotspot - t_ambient
    if delta_t <= 0:
        return 0.0
    return delta_t / (i_rms ** 2 * theta_thermal)


def expected_delta_t_closed_form(i_rms: float, r_nominal_ohms: float, theta_thermal: float) -> float:
    """
    The forward direction of the same model: the temperature rise a
    joint AT THIS JOINT'S OWN LEARNED HEALTHY RESISTANCE (r_nominal_ohms,
    from app/baseline.py) would show at this I_rms. Kept separate from
    the TESPy-based forward model (app/physics/tespy_model.py) purely so
    the pytest suite has a library-free reference answer to check the
    TESPy path against - see tests/test_physics.py.
    """
    return i_rms ** 2 * r_nominal_ohms * theta_thermal